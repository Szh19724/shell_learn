#!/usr/bin/env bash
# =============================================================================
# 第3章 正则表达式 · 练习1：元字符（配合 grep -E，Linux 环境）
#
# 用法：
#   1. 把每题 regex='___' 中的 ___ 换成你的正则表达式（ERE 语法）
#   2. 运行：bash 01-元字符练习.sh          （或 chmod +x 后 ./01-元字符练习.sh）
#   3. 脚本自动判题；卡住了看每题上方的「参考答案」注释
#
# 演示模式：bash 01-元字符练习.sh --demo   （自动用参考答案跑一遍，验证答案）
#
# 要点：
#   - grep -E 用的是"扩展正则 ERE"：+ * ? { } ( ) 直接写，不加反斜杠
#   - 想让元字符表示它本身（比如点 .），才需要写 \.
#   - 教材里 * 叫"惰性"是强调它"匹配0个也算成功"；
#     严格说 + 和 * 都是贪婪匹配，惰性（懒惰）写法是 a+? a*? 这种
# =============================================================================

USE_ANSWER=0
[ "${1:-}" = "--demo" ] && USE_ANSWER=1

pass=0; fail=0; skip=0

# 判题函数：
#   check "题目描述" "你的正则" "参考答案" "+应匹配的串" "-不应匹配的串" ...
check() {
    local desc="$1" re="$2" ans="$3"
    shift 3
    [ "$USE_ANSWER" = 1 ] && re="$ans"
    if [ -z "$re" ] || [ "$re" = "___" ]; then
        echo "[未作答] $desc"
        echo "         参考答案: $ans"
        skip=$((skip + 1))
        return
    fi
    local ok=1 spec text rc
    for spec in "$@"; do
        text="${spec:1}"
        grep -E -q -- "$re" <<< "$text"
        rc=$?
        if [ $rc -ge 2 ]; then
            echo "[正则有误] $desc"
            echo "           grep 无法解析：$re"
            fail=$((fail + 1))
            return
        fi
        [ "${spec:0:1}" = "+" ] && [ $rc -ne 0 ] && ok=0
        [ "${spec:0:1}" = "-" ] && [ $rc -eq 0 ] && ok=0
    done
    if [ $ok -eq 1 ]; then
        echo "[通过] $desc"
        pass=$((pass + 1))
    else
        echo "[失败] $desc   你的正则: $re"
        echo "       参考答案: $ans"
        fail=$((fail + 1))
    fi
}

echo "===== 练习1：元字符 ====="

# ---------------------------------------------------------------------------
# 练习1：. 匹配任意单个字符
# 参考答案: c.t
# ---------------------------------------------------------------------------
regex='___'
check "1.1 用 . 匹配 cat/cut/cot，但不匹配 ct/cart" "$regex" 'c.t' \
    '+cat' '+cut' '+cot' '-ct' '-cart'

# ---------------------------------------------------------------------------
# 练习2：[] 字符组，一次只匹配其中"一个"字符；- 表示范围
# 参考答案: [13579]
# ---------------------------------------------------------------------------
regex='___'
check "2.1 只匹配奇数数字 1/3/5/7/9，不匹配 2/4/6/8/0" "$regex" '[13579]' \
    '+1' '+3' '+5' '+7' '+9' '-2' '-4' '-6' '-8' '-0'

# ---------------------------------------------------------------------------
# 练习3：\w 匹配 字母、数字、下划线
# 参考答案: \w+
# ---------------------------------------------------------------------------
regex='___'
check "3.1 匹配标识符 total_42 / x / A1，但不匹配 . - +" "$regex" '\w+' \
    '+total_42' '+x' '+A1' '-.' '--' '-+'

# ---------------------------------------------------------------------------
# 练习4：+ 匹配"一个或多个"前面的字符（贪婪）
# 参考答案: ab+
# ---------------------------------------------------------------------------
regex='___'
check "4.1 匹配 ab/abb/abbb，但不匹配 a/b/ba" "$regex" 'ab+' \
    '+ab' '+abb' '+abbb' '-a' '-b' '-ba'

# ---------------------------------------------------------------------------
# 练习5：* 匹配"零个或多个"前面的字符
# 参考答案: ab*
# ---------------------------------------------------------------------------
regex='___'
check "5.1 匹配 a/ab/abb，但不匹配 b/cb" "$regex" 'ab*' \
    '+a' '+ab' '+abb' '-b' '-cb'

# ---------------------------------------------------------------------------
# 练习6：? 匹配"零个或一个"前面的字符
# 参考答案: colou?r
# ---------------------------------------------------------------------------
regex='___'
check "6.1 匹配 color/colour，但不匹配 colouur/colr" "$regex" 'colou?r' \
    '+color' '+colour' '-colouur' '-colr'

# ---------------------------------------------------------------------------
# 练习7：{数字} 匹配固定个数
# 参考答案: a{3}
# ---------------------------------------------------------------------------
regex='___'
check "7.1 匹配含 3 个连续 a 的串（aaa/xaaay），但不含 aa/a" "$regex" 'a{3}' \
    '+aaa' '+xaaay' '-aa' '-a'

# ---------------------------------------------------------------------------
# 练习8：{min,} 至少 min 个
# 参考答案: a{3,}
# ---------------------------------------------------------------------------
regex='___'
check "8.1 匹配 3 个及以上连续 a，但不匹配 aa/a" "$regex" 'a{3,}' \
    '+aaa' '+aaaaaa' '-aa' '-a'

# ---------------------------------------------------------------------------
# 练习9：{min,max} 至少 min 个、至多 max 个
# 参考答案: a{2,3}
# ---------------------------------------------------------------------------
regex='___'
check "9.1 匹配 2~3 个连续 a（aa/aaa），但不匹配 a/b" "$regex" 'a{2,3}' \
    '+aa' '+aaa' '-a' '-b'

# ---------------------------------------------------------------------------
# 练习10：() 孑模式，把括号里看成一个整体（教材例子）
# 参考答案: (12+)+
# ---------------------------------------------------------------------------
regex='___'
check "10.1 匹配 12/122/1212/12221222，但不匹配 1/2/21" "$regex" '(12+)+' \
    '+12' '+122' '+1212' '+12221222' '-1' '-2' '-21'

# ---------------------------------------------------------------------------
# 进阶：^ 行首、$ 行尾锚点（grep 默认匹配"任意位置"，锚点可精确到整行）
# 参考答案: ^[0-9]{4}-[0-9]{2}-[0-9]{2}$
# ---------------------------------------------------------------------------
regex='___'
check "进阶.1 匹配整行日期 2024-05-01，不匹配 2024-5-1 / 20240501" "$regex" \
    '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' \
    '+2024-05-01' '-2024-5-1' '-20240501' '-x 2024-05-01'

echo "----------------------------------------"
echo "通过 $pass，失败 $fail，未作答 $skip"
[ "$fail" -gt 0 ] && exit 1
exit 0
