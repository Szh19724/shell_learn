#!/usr/bin/env bash
# =============================================================================
# 第3章 正则表达式 · 练习2：从日志中匹配 IP 地址（grep / sed 实战）
#
# 用法：
#   1. 把每题 cmd='___' 中的 ___ 换成你的命令（管道可以随便组合）
#   2. 运行：bash 02-IP地址匹配练习.sh
#   3. 脚本自动比对输出；卡住了看每题上方的「参考答案」
#
# 演示模式：bash 02-IP地址匹配练习.sh --demo
#
# 本章核心结论（匹配 IP 的三个阶段）：
#   粗匹配：[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+
#   分段限定1~3位：[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}
#   精简写法：([0-9]{1,3}\.){3}[0-9]{1,3}
#   注意：正则只管"形状"，999.999.999.999 形状合法但不是真 IP，校验 0~255 要靠程序
# =============================================================================

USE_ANSWER=0
[ "${1:-}" = "--demo" ] && USE_ANSWER=1

pass=0; fail=0; skip=0

# 一段"日志"，故意混入假 IP 和干扰项
LOG=$(cat <<'EOF'
2024-05-01 08:15:01 INFO  192.168.31.101 user login ok
2024-05-01 08:15:02 WARN  10.0.0.256 ip out of range (每段应<=255)
2024-05-01 08:15:03 INFO  172.16.0.7 proxy connected
2024-05-01 08:15:04 ERROR 999.999.999.999 invalid (每段应<=255)
2024-05-01 08:15:05 INFO  192.168.31.101 user logout
2024-05-01 08:15:06 INFO  127.0.0.1 health check ok
2024-05-01 08:15:07 INFO  10.0.0.256 retry
2024-05-01 08:15:09 WARN  bad ip 192.168.31.1015 typed (手滑多打一位)
2024-05-01 08:15:10 INFO  config from 1.2.3 (只有三段，不是IP)
EOF
)

# 归一化：压缩空白、去首尾空格，方便比对
norm() {
    printf '%s\n' "$1" | sed -e 's/[[:space:]]\{1,\}/ /g' -e 's/^ //' -e 's/ $//'
}

# 判题函数：
#   run "题目描述" "你的命令" "参考命令" "期望输出"
run() {
    local desc="$1" cmd="$2" ans="$3" expected="$4"
    [ "$USE_ANSWER" = 1 ] && cmd="$ans"
    if [ -z "$cmd" ] || [ "$cmd" = "___" ]; then
        echo "[未作答] $desc"
        echo "         参考命令: $ans"
        skip=$((skip + 1))
        return
    fi
    local actual
    actual=$(eval "$cmd" 2>&1)
    if [ "$(norm "$actual")" = "$(norm "$expected")" ]; then
        echo "[通过] $desc"
        pass=$((pass + 1))
    else
        echo "[失败] $desc"
        echo "       你的输出: $(norm "$actual" | head -5 | tr '\n' '|')"
        echo "       期望输出: $(norm "$expected" | tr '\n' '|')"
        echo "       参考命令: $ans"
        fail=$((fail + 1))
    fi
}

echo "===== 练习2：从日志中匹配 IP 地址 ====="
echo "----- 日志 -----"
printf '%s\n' "$LOG"
echo "----------------"

# ---------------------------------------------------------------------------
# 练习1：先匹配"点分式字符串"（教材第一步，四段数字用点连接，不管大小）
# 参考答案: printf '%s\n' "$LOG" | grep -oE '[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+'
# 提示: grep -o 只输出匹配到的部分
# ---------------------------------------------------------------------------
cmd='___'
run "1.1 提取日志里所有点分式（含假IP，注意 1015 会被整个吃掉）" "$cmd" \
    'printf "%s\n" "$LOG" | grep -oE "[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+"' \
    '192.168.31.101
10.0.0.256
172.16.0.7
999.999.999.999
192.168.31.101
127.0.0.1
10.0.0.256
192.168.31.1015'

# ---------------------------------------------------------------------------
# 练习2：每段限定 1~3 位（精简写法）
# 参考答案: printf '%s\n' "$LOG" | grep -oE '([0-9]{1,3}\.){3}[0-9]{1,3}'
# 现象观察: 192.168.31.1015 这次只截出 192.168.31.101 —— 正则只管形状，
#          多打的那位数字留下一个孤零零的 5，真正校验要靠程序判断 0~255
# ---------------------------------------------------------------------------
cmd='___'
run "2.1 用精简写法提取 IP（每段1~3位）" "$cmd" \
    'printf "%s\n" "$LOG" | grep -oE "([0-9]{1,3}\.){3}[0-9]{1,3}"' \
    '192.168.31.101
10.0.0.256
172.16.0.7
999.999.999.999
192.168.31.101
127.0.0.1
10.0.0.256
192.168.31.101'

# ---------------------------------------------------------------------------
# 练习3：统计出现最多的 IP（sort | uniq -c | sort -rn 组合拳）
# 参考答案: printf '%s\n' "$LOG" | grep -oE '([0-9]{1,3}\.){3}[0-9]{1,3}' | sort | uniq -c | sort -rn | head -1
# ---------------------------------------------------------------------------
cmd='___'
run "3.1 找出出现次数最多的 IP 及其次数" "$cmd" \
    'printf "%s\n" "$LOG" | grep -oE "([0-9]{1,3}\.){3}[0-9]{1,3}" | sort | uniq -c | sort -rn | head -1' \
    '3 192.168.31.101'

# ---------------------------------------------------------------------------
# 练习4：用 sed 把 IP 打码（脱敏），再数一数打了几处
# 参考答案(打码): printf '%s\n' "$LOG" | sed -E 's/([0-9]{1,3}\.){3}[0-9]{1,3}/<IP>/g' | grep -c '<IP>'
# ---------------------------------------------------------------------------
cmd='___'
run "4.1 用 sed 把所有 IP 替换成 <IP>，输出被打码的行数" "$cmd" \
    'printf "%s\n" "$LOG" | sed -E "s/([0-9]{1,3}\.){3}[0-9]{1,3}/<IP>/g" | grep -c "<IP>"' \
    '8'

# ---------------------------------------------------------------------------
# 练习5：打码之后，日志里不应该再有"点分式"了
# 参考答案: printf '%s\n' "$LOG" | sed -E 's/([0-9]{1,3}\.){3}[0-9]{1,3}/<IP>/g' | grep -cE '([0-9]{1,3}\.){3}[0-9]{1,3}'
# ---------------------------------------------------------------------------
cmd='___'
run "5.1 打码后的日志里，残留的点分式数量应为 0" "$cmd" \
    'printf "%s\n" "$LOG" | sed -E "s/([0-9]{1,3}\.){3}[0-9]{1,3}/<IP>/g" | grep -cE "([0-9]{1,3}\.){3}[0-9]{1,3}"' \
    '0'

# ---------------------------------------------------------------------------
# 进阶（可选）：把每段限制到 0~255，过滤掉假 IP（需要 GNU grep 的 -P）
# 参考答案见下方；若你的 grep 不支持 -P 会自动跳过
# ---------------------------------------------------------------------------
echo "----- 进阶：过滤 0~255 的真 IP -----"
if printf 'a\n' | grep -Pq 'a' 2>/dev/null; then
    cmd='___'
    run "进阶.1 只输出合法 IP（256/999/1015 都要被排除）" "$cmd" \
        'printf "%s\n" "$LOG" | grep -oP "\b((25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])\.){3}(25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])\b"' \
        '192.168.31.101
172.16.0.7
192.168.31.101
127.0.0.1'
else
    echo "[跳过] 本机 grep 不支持 -P，进阶题跳过（Linux 上 GNU grep 一般都支持）"
fi

echo "----------------------------------------"
echo "通过 $pass，失败 $fail，未作答 $skip"
[ "$fail" -gt 0 ] && exit 1
exit 0
